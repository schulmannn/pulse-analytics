// ═══════════════════════════════════════════════════════════════
//  Atlavue — письмо подтверждения email (общий шаблон)
// ═══════════════════════════════════════════════════════════════
// Один шаблон на два флоу: обычную регистрацию (routes/auth.js) и приём приглашения по раскрытой
// ссылке (routes/team.js, H-1). Раньше он был замыканием внутри auth.js; вынесен, чтобы второй
// вызывающий не завёл свою копию и тексты не разъехались.
//
// Вариант `passwordUnusable` — для claim по раскрытой ссылке: пароль, введённый открывшим ссылку,
// сервер НЕ сохраняет (её мог открыть не владелец ящика), поэтому письмо честно говорит, что после
// подтверждения пароль задаётся через «Забыли пароль».

'use strict';

function createVerifyEmail({ emailShell, emailBtn }) {
  return function verifyEmailHtml(link, { passwordUnusable = false } = {}) {
    const tail = passwordUnusable
      ? '<p>Ссылка действует 24 часа. После подтверждения задайте пароль через «Забыли пароль» на странице входа — пароль, введённый по ссылке приглашения, не сохранён.</p>'
      : '<p style="color:#64748d;font-size:13px">Ссылка действует 24 часа. Если это были не вы — проигнорируйте письмо.</p>';
    return emailShell('Подтверди email',
      `<p>Активируй аккаунт в Atlavue:</p>${emailBtn(link, 'Подтвердить email')}${tail}`);
  };
}

module.exports = { createVerifyEmail };
