// ═══════════════════════════════════════════════════════════════
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Паттерн жил тремя копиями (register, forgot в routes/auth.js и приглашения
// в routes/team.js), и все три были уязвимы к ReDoS (аудит, AUTH-1): в `/^[^@\s]+@[^@\s]+\.[^@\s]+$/`
// оба класса домена захватывают точку, поэтому строка «a@» + сто тысяч точек + «@» разбирается
// бэктрекингом за O(n²). Тело в 100 КБ (предел express.json) держало единственный Node-процесс
// около 20 с на ОДИН анонимный запрос, а authLimiter пропускает двадцать таких за окно.
//
// Две защиты, и каждая закрывает атаку сама по себе:
//   • длина режется ДО регулярки: адрес длиннее 254 символов (RFC 5321, путь 256 минус «<>») не
//     бывает, и в регулярку больше не попадает ничего, что стоит заметного времени;
//   • сам паттерн однозначный: метки домена не содержат точку, поэтому разбиение «метка.метка»
//     единственное и разбор линеен по длине строки при любом входе.
// Новый паттерн строже старого ровно на пустых метках домена («a@b..c», «a@.b.c», «a@b.c.») —
// такие адреса почта не доставит, а обычные адреса он принимает так же.

'use strict';

const MAX_EMAIL_LENGTH = 254;
const EMAIL_RE = /^[^@\s]+@[^@\s.]+(?:\.[^@\s.]+)+$/;

/** Похоже ли значение на email. Ожидает уже нормализованную строку (toLowerCase().trim()). */
function isPlausibleEmail(value) {
  if (typeof value !== 'string' || value.length > MAX_EMAIL_LENGTH) return false;
  return EMAIL_RE.test(value);
}

module.exports = { MAX_EMAIL_LENGTH, isPlausibleEmail };
