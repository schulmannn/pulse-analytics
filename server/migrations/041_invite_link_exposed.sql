-- 041_invite_link_exposed.sql
-- Закрывает pre-account takeover через приглашение (аудит #554, H-1).
--
-- Разбор дыры. Сырой токен приглашения отдаётся ИНИЦИАТОРУ в двух местах: в ответе на выпуск
-- (`invite_link`) и по кнопке «показать ссылку». Публичный /claim по этому токену создавал сразу
-- ACTIVE-аккаунт на чужой email с паролем, который выбирает открывший ссылку, и выдавал ему cookie
-- на 30 дней. Владелец воркспейса мог таким образом завести живой аккаунт на любой ящик, а
-- последующий вход настоящего хозяина через Google этот аккаунт не сбрасывал.
--
-- Инвариант, который вводит эта миграция: если ссылка ХОТЬ РАЗ была показана инициатору, доставка
-- письма больше не доказывает владение ящиком, и активировать аккаунт по такой ссылке нельзя —
-- только создать unverified и отправить обычное письмо подтверждения.
--
-- Forward-only + идемпотентно.

ALTER TABLE workspace_invites ADD COLUMN IF NOT EXISTS link_exposed_at TIMESTAMPTZ;

-- Происхождение аккаунта: 'invite_claim' = создан публичным /claim по ссылке приглашения.
-- Нужен вход в Google-ветку auth.js — такой аккаунт при первом входе настоящего владельца обязан
-- отозвать все сессии и обнулить пароль, даже если он уже 'active'.
ALTER TABLE users ADD COLUMN IF NOT EXISTS created_via TEXT;

-- Бэкфилл для окна, которое уже случилось в проде: до этой миграции /claim создавал active-аккаунты
-- и никакого признака не оставлял. Отличаем claim от обычного приёма приглашения по времени: у
-- claim-аккаунта строка users появилась НЕ РАНЬШЕ самого приглашения (аккаунта до него не было),
-- у обычного /accept аккаунт существовал заранее. Ошибка в консервативную сторону: лишняя пометка
-- стоит одного повторного входа, пропущенная — оставляет чужой доступ.
UPDATE users u
   SET created_via = 'invite_claim'
  FROM workspace_invites i
 WHERE u.created_via IS NULL
   AND i.accepted_uid = u.id
   AND lower(i.email) = lower(u.email)
   AND u.created_at >= i.created_at;
