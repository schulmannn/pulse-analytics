-- ── Rusender: семья составной рассылки (A/B-варианты и досылы) ───────────────
-- ADDITIVE-ONLY + идемпотентно, откат = git revert.
--
-- ЗАЧЕМ. У Rusender рассылка бывает СОСТАВНОЙ: базовая + её части (`parts[]` — варианты
-- A/B-теста или досыл). Спека прямо предупреждает, что `stats` базовой рассылки В СПИСКЕ —
-- это АГРЕГАТ ПО СЕМЬЕ, тогда как в `get-by-id` у той же рассылки лежат её СОБСТВЕННЫЕ цифры.
-- Если при этом варианты приезжают ещё и отдельными строками списка, наивная `SUM(delivered)`
-- посчитает семью ДВАЖДЫ — ровно тот класс ошибки, что альбомы Telegram (схлопывать по
-- `grouped_id`, иначе двойной счёт постов и просмотров).
--
-- Проверить это на живом аккаунте владельца пока НЕЧЕМ (составных рассылок у него может не
-- быть вовсе), поэтому защита сделана СТРУКТУРНОЙ, а не «по факту замера»: часть семьи хранит
-- ссылку на свою базу, и любая витрина, считающая итоги, суммирует ТОЛЬКО базовые строки
-- (`parent_id IS NULL`). Тогда обе возможные реальности безопасны:
--   • варианты приходят отдельными строками  → они помечены parent_id и в итоги не входят;
--   • варианты в списке не приходят вовсе    → строк с parent_id просто нет, поведение прежнее.
-- Сами варианты остаются в архиве целиком: «вариант A против варианта B» — законный вопрос
-- ленты и разворота, его нельзя терять ради безопасности сумм.

ALTER TABLE rusender_campaigns ADD COLUMN IF NOT EXISTS parent_id BIGINT;
-- Роль части в семье: ab_variant | follow_up. NULL — самостоятельная рассылка или база семьи.
ALTER TABLE rusender_campaigns ADD COLUMN IF NOT EXISTS family_role TEXT;

-- Итоговые запросы фильтруют `parent_id IS NULL` по каналу — частичный индекс держит этот
-- горячий путь узким (у семьи частей обычно 1-3, но у ленты рассылок фильтр постоянный).
CREATE INDEX IF NOT EXISTS rusender_campaigns_base_idx
  ON rusender_campaigns (channel_id, started_at DESC)
  WHERE parent_id IS NULL;

-- Разворот семьи: «покажи части этой базовой рассылки».
CREATE INDEX IF NOT EXISTS rusender_campaigns_parent_idx
  ON rusender_campaigns (channel_id, parent_id)
  WHERE parent_id IS NOT NULL;
