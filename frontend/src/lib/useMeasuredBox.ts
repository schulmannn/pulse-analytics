import { useEffect, useLayoutEffect, useState } from 'react';
import { observeSize } from '@/lib/observeSize';

/**
 * Замер идёт в LAYOUT-фазе, а не после кадра. Иначе первый кадр рисуется по константе-предположению,
 * второй — по факту, и список на глазах схлопывается с пяти строк до четырёх: пользователь видит
 * дёрганье, а тест ловит промежуточное состояние и становится флаки. На сервере (юниты через
 * renderToStaticMarkup) layout-эффект недоступен и не нужен — разметка там всё равно не меряется,
 * и обе стороны получают одно и то же предположение.
 */
export const useIsoLayoutEffect = typeof window === 'undefined' ? useEffect : useLayoutEffect;

/**
 * Фактическая высота блока, который занимает место в бюджете тайла, но строкой списка не является
 * (шапка колонок разбивки).
 *
 * ЗАЧЕМ ЗАМЕР, А НЕ КОНСТАНТА. Высота шапки складывается из кегля `text-2xs`, отступов и
 * hairline-границы — три независимых источника, любой из которых меняется в токенах, а не здесь.
 * Ровно так константа шага строки уже разошлась с вёрсткой и порезала карточки на восьми разрезах
 * Метрики (#616). Замер самоисправляется, константа — нет.
 *
 * Второе, что даёт замер бесплатно: шапка живёт под `sm:` и ниже 640px её `display:none` —
 * `offsetHeight` там честный ноль, поэтому мобильный бюджет строк остаётся ровно прежним без
 * отдельной ветки на media-query.
 *
 * ССЫЛКА — КОЛБЭЧНАЯ, а не `useRef`. Разбивка сначала рендерит пустое состояние и только потом,
 * с приходом данных, саму шапку: с object-ref эффект отработал бы один раз на `null`, больше не
 * проснулся бы (deps не изменились) и замера НЕ БЫЛО БЫ ВООБЩЕ — тихо, с молчаливым откатом на
 * константу. Колбэк меняет состояние в момент появления узла, и эффект перезапускается.
 *
 * `fallback` — предположение ТОЛЬКО до первого замера: оно должно быть близко к правде, иначе
 * первый кадр отдаст лишнюю строку в тайл, который её не держит.
 */
export function useMeasuredBox(fallback: number): {
  ref: (node: HTMLElement | null) => void;
  height: number;
} {
  const [node, setNode] = useState<HTMLElement | null>(null);
  const [height, setHeight] = useState<number | null>(null);
  useIsoLayoutEffect(() => {
    if (!node) {
      setHeight(null);
      return;
    }
    // Обновляемся только при расхождении больше пикселя — иначе округления гоняли бы ре-рендер
    // по кругу. Ноль — валидный результат (скрытая на узком экране шапка).
    const measure = () =>
      setHeight((prev) => {
        const next = node.offsetHeight;
        return prev != null && Math.abs(prev - next) <= 1 ? prev : next;
      });
    measure();
    // Пере-замер по ResizeObserver: ширина тайла меняет и перенос подписи, и видимость шапки.
    return observeSize(node, measure);
  }, [node]);
  return { ref: setNode, height: height ?? fallback };
}
