// До этого тело карточки о своём размере не знало: ChartSection считает `effectiveSize` (S/M/L),
// вешает по нему высоту и колонки, а внутрь не передаёт. Виджету «Неделя канала» это нужно, потому
// что у него ДВА макета, а не один растянутый: в L — число, полоска ритма и одна мысль; в M и S —
// та же информация списком фактов, без графика. Ужимать L до 264px бессмысленно: полоска в такой
// высоте вырождается, а проза не помещается.
//
// Контейнерными запросами это не решается: `@container tile` знает ширину и высоту тайла, но не
// знает, ВЫБРАЛ ли владелец размер S — а выбор владельца и есть то, чему тело должно подчиняться.
//
// Дефолт `full` — для всего, что рендерится ВНЕ карточки: expand-оверлей, превью в редакторе,
// страницы метрик. Там места столько же, сколько у L, и вести себя надо как L.
import { createContext, useContext } from 'react';
import type { WidgetSize } from '@/lib/widgetPrefsStore';

export const WidgetSizeContext = createContext<WidgetSize>('full');

/** Размер карточки, в теле которой мы находимся; вне карточки — `full`. */
export function useWidgetSize(): WidgetSize {
  return useContext(WidgetSizeContext);
}
