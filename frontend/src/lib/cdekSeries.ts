import type { CdekPoint } from '@/api/cdek';

/**
 * Календарная сетка окна честными нулями.
 *
 * Сервер СДЭКа отдаёт ТОЛЬКО дни, в которых были продажи («Пустые корзины НЕ достраиваются» —
 * getCdekSeriesForActor), и уплотнить их обязан фронт: он один знает, что «нет заказов» здесь ноль,
 * а не пропуск данных. У МойСклада это делает densifyDayPoints, у СДЭКа не делал никто, и разреженный
 * ряд ломал сразу три вещи:
 *
 *   • ОСЬ ВРАЛА. 29 июля и 3 августа вставали соседними точками, если между ними не было продаж:
 *     подписи дат оставались настоящими, а расстояния между ними — нет.
 *   • СРАВНЕНИЕ МОЛЧА ПРОПАДАЛО на столбцах. BarChart требует, чтобы призрак совпадал с рядом по
 *     длине (иначе i-й столбец сравнивался бы с чужим днём), а у окон было 25 и 30 точек —
 *     сравнение считалось в rail'е и не рисовалось на полотне. Владелец: «на бар чартах не видно
 *     сравнения».
 *   • СЧЁТ ЦЕЛИ шёл по дням С ПРОДАЖАМИ: «достигнута в 0 из 25 дней» на тридцатидневном окне.
 *
 * Нули ставятся только в СЫРЫЕ величины (выручка, заказы, штуки). Производные вроде среднего чека
 * считаются после — их `pick` сам вернёт null там, где заказов ноль, и штриховка разрыва останется
 * честной: «в этот день не с чего считать средний чек» ≠ «средний чек равен нулю».
 */
export function densifyCdekDays(
  points: readonly CdekPoint[],
  from: string | null | undefined,
  to: string | null | undefined,
): CdekPoint[] {
  if (!from || !to) return [...points];
  const start = Date.parse(`${from}T00:00:00Z`);
  const end = Date.parse(`${to}T00:00:00Z`);
  if (!Number.isFinite(start) || !Number.isFinite(end) || end < start) return [...points];
  // Защита от абсурдного окна: сетку строим не длиннее трёх лет, иначе кривой ответ сервера
  // обернулся бы миллионом узлов в памяти.
  const days = Math.round((end - start) / 86_400_000) + 1;
  if (days > 1100) return [...points];

  const byDay = new Map(points.map((p) => [p.day, p]));
  const out: CdekPoint[] = [];
  for (let i = 0; i < days; i += 1) {
    const key = new Date(start + i * 86_400_000).toISOString().slice(0, 10);
    const hit = byDay.get(key);
    out.push(hit ?? { day: key, revenue: 0, orders: 0, items: 0 });
  }
  return out;
}
