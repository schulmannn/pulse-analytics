/**
 * Разделы страницы /analytics — единственный источник ключей и подписей второго уровня навигации.
 *
 * Живут в `lib/`, а не в самой панели, потому что подписи нужны ещё и ⌘K-палитре: она ленивый чанк,
 * и импорт из `panels/AnalyticsTabs.tsx` затащил бы в него всю аналитику (TgAnalytics, Charts,
 * Compare) — та же грабля бюджета, из-за которой IG-метрики в палитре перечислены вручную.
 *
 * Порядок повторяет каноническую схему секций (динамика/охват → агрегаты по типам → аудитория →
 * сравнение). Вкладка называется «Форматы», а не «Контент»: раздел сайдбара «Контент» (список
 * публикаций) уже занял это имя — два «Контента» в клике друг от друга читаются как одно и то же.
 * Эта вкладка — агрегаты ПО ТИПАМ (форматы, эмодзи, хэштеги).
 */
export const ANALYTICS_TABS = [
  { key: 'dynamics', label: 'Динамика' },
  { key: 'content', label: 'Форматы' },
  { key: 'audience', label: 'Аудитория' },
  { key: 'compare', label: 'Сравнение' },
] as const;

export type AnalyticsTab = (typeof ANALYTICS_TABS)[number]['key'];

export const isAnalyticsTab = (raw: string | null): raw is AnalyticsTab =>
  ANALYTICS_TABS.some((t) => t.key === raw);
