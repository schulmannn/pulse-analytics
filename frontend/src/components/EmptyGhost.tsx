/**
 * Призрак формы — силуэт того графика, который карточка нарисует, когда данные появятся.
 *
 * ЗАЧЕМ. Пустая карточка сегодня — полоса воздуха со значком: по ней не видно, что здесь вообще
 * должно быть, и шесть неподключённых карточек подряд читаются как одна сломанная страница.
 * Силуэт возвращает карточке её обещание («тут будет линия / столбцы / рейтинг / доля») ещё до
 * первого числа — референс Reown/Linktree, взятый узко: только форма, без иллюстраций и блюра,
 * которые канон Atlavue отвергает (DESIGN_TOKENS.md).
 *
 * ФОРМА НЕ ИЗ ДАННЫХ. Геометрия зашита константами и одинакова на всех карточках одного вида.
 * Силуэт, посчитанный из чего-либо живого, рисовал бы динамику, которой не измеряли, — это ровно
 * та ложь, ради борьбы с которой в продукте есть honesty-гарды. Линия к тому же симметрична: у
 * неё физически нет наклона, поэтому её нельзя прочитать как рост или падение.
 *
 * НЕ ПУТАТЬ с «призраком прошлого периода» (`GHOST_ALPHA` в BarChart, `--chart-role-comparison`):
 * тот рисует РЕАЛЬНЫЕ числа прошлого окна и обязан держать non-text 3.0. Этот — декорация в
 * строгом смысле WCAG 1.4.11 (никакой информации, `aria-hidden`), и наоборот ОБЯЗАН остаться
 * заметно бледнее любой линии данных, иначе пустая карточка притворится наполненной.
 */
import type { JSX } from 'react';
import { cn } from '@/lib/utils';

/** Четыре природы карточек продукта: серия, столбцы, список строк, доля целого. */
export type EmptyGhost = 'line' | 'bars' | 'rows' | 'ring';

/**
 * Краска силуэта — ЛИТЕРАЛ, а не собранная строка.
 *
 * Во-первых, Tailwind сканирует исходники и класс с вычисленной альфой просто не попал бы в
 * сборку. Во-вторых, `scripts/contrast-tokens.mjs` вытаскивает альфу из этой самой строки и
 * держит её в коридоре «виднее волосяной линии, но заведомо бледнее данных»: разъехаться коду и
 * гейту негде. Замер на светлой карточке: 1.40 против 5.48 у полноцветного muted.
 */
export const EMPTY_GHOST_INK = 'text-muted-foreground/25';

/** Полштриха отступа от края viewBox: обводка рисуется ПО контуру, и фигура вплотную к границе
 *  теряет внешнюю половину штриха под обрезкой — у крайнего столбца пропадала бы боковая грань. */
const INSET = 0.75;

/** Высоты столбцов: почти ровный гребень — ни ступеньки вверх, ни обвала. */
const BAR_HEIGHTS = [18, 26, 14, 30, 22, 34, 20, 28, 16, 32, 24, 30];
const BAR_W = 8;
const BAR_STEP = (160 - 2 * INSET - BAR_W) / (BAR_HEIGHTS.length - 1);
/** Геометрия считается ОДИН раз на модуль, а не на каждый рендер: она константа по определению
 *  (см. шапку), и заодно у прямоугольников появляется собственный ключ вместо индекса массива. */
const BARS = BAR_HEIGHTS.map((h, i) => ({
  id: `bar-${i}`,
  x: +(INSET + i * BAR_STEP).toFixed(2),
  y: 48 - INSET - h,
  h,
}));

/** Строки рейтинга: убывающие — это и есть форма «списка по убыванию». */
const ROW_H = 6;
const ROW_STEP = (48 - 2 * INSET - ROW_H) / 3;
const ROWS = [140, 104, 72, 48].map((w, i) => ({ id: `row-${i}`, y: +(INSET + i * ROW_STEP).toFixed(2), w }));

/** Семь точек линии, зеркальные относительно центра (см. шапку — у призрака нет тренда). */
const LINE_YS = [26, 14, 22, 10, 22, 14, 26];
const LINE_X0 = 2;
const LINE_STEP = 26;

const LINE_PATH = LINE_YS.map((y, i) => `${i === 0 ? 'M' : 'L'}${LINE_X0 + i * LINE_STEP} ${y}`).join('');

/** Общая обводка всех растянутых форм — 1.5px в ЭКРАННЫХ пикселях (см. `vector-effect` ниже). */
const OUTLINE = {
  fill: 'none',
  stroke: 'currentColor',
  strokeWidth: 1.5,
  vectorEffect: 'non-scaling-stroke',
} as const;

/**
 * `preserveAspectRatio="none"` — силуэт тянется на всю полосу карточки, как и настоящие графики
 * продукта. Отсюда обязательный `vector-effect` на обводке (канон CLAUDE.md: иначе неравномерное
 * растяжение размазывает штрих). Кольцо — исключение: круг, растянутый в эллипс, перестаёт быть
 * кольцом, поэтому у него `meet` и, как следствие, штрих масштабируется честно и без vector-effect.
 */
export function EmptyGhostShape({ kind, className }: { kind: EmptyGhost; className?: string }): JSX.Element {
  const common = {
    'aria-hidden': true as const,
    focusable: 'false' as const,
    'data-slot': 'empty-ghost',
    'data-ghost': kind,
  };

  if (kind === 'ring') {
    return (
      <svg
        {...common}
        viewBox="0 0 48 48"
        preserveAspectRatio="xMidYMid meet"
        className={cn(EMPTY_GHOST_INK, className)}
      >
        {/* ТРИ дольки по всей окружности, а не одна дуга на 270°: длина окружности r=18 — 113.1,
            период 37.7 (31.7 штрих + 6 пропуск) укладывается в неё ровно три раза. Одиночная
            дуга на три четверти — это в точности идиома спиннера, и призрак пустоты читался бы
            как «идёт загрузка»; ровно ту границу, ради которой он статичен, это и стирало бы.
            Старт с двенадцати часов — как рисует дольки настоящий PieChart. */}
        <circle
          cx="24"
          cy="24"
          r="18"
          fill="none"
          stroke="currentColor"
          strokeWidth="6"
          strokeDasharray="31.7 6"
          transform="rotate(-90 24 24)"
        />
      </svg>
    );
  }

  return (
    <svg
      {...common}
      viewBox="0 0 160 48"
      preserveAspectRatio="none"
      className={cn(EMPTY_GHOST_INK, className)}
    >
      {/* ВСЕ виды — обводка без заливки. Залитые столбцы и строки при той же альфе читаются как
          настоящий график «в тумане» (тот же объект, только тусклее) и как ряды скелетона
          загрузки — то есть стирают обе границы разом. Контур говорит другое: форма обещана,
          содержимого нет. Заливка тут — не вопрос вкуса, а вопрос честности карточки. */}
      {kind === 'line' ? (
        <path d={LINE_PATH} {...OUTLINE} />
      ) : kind === 'bars' ? (
        BARS.map((bar) => <rect key={bar.id} x={bar.x} y={bar.y} width={BAR_W} height={bar.h} {...OUTLINE} />)
      ) : (
        ROWS.map((row) => (
          <rect key={row.id} x={INSET} y={row.y} width={row.w} height={ROW_H} rx="3" {...OUTLINE} />
        ))
      )}
    </svg>
  );
}
