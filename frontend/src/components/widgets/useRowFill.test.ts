import { describe, expect, it } from 'vitest';
import { fillTargetIndex } from './useRowFill';

/**
 * ПРАВИЛО ЗАПОЛНЕНИЯ РЯДА — кому достаётся остаток свободных колонок (аудит #554, проход №2, N4).
 *
 * Сама раскладка меряется в браузере, а вот РЕШЕНИЕ — чистое, и именно в нём была дыра: правило
 * смотрело только на последнюю карточку ряда и, если она не подходила, отступалось молча.
 *
 * Воспроизвести случай в e2e нельзя: он требует СОХРАНЁННОГО размера карточки, то есть настроек
 * владельца, которых в демо нет. Поэтому решение и вынесено — иначе гейт остался бы зелёным на
 * дыре в 230px, как и был.
 */

describe('fillTargetIndex', () => {
  it('обычный ряд: остаток берёт последняя карточка', () => {
    expect(fillTargetIndex([false, false])).toBe(1);
  });

  it('последняя со своим размером — растёт предыдущая, а не никто', () => {
    // Ровно случай Аналитики: «Просмотры» (растяжимая) + «Динамика оттока» (user-sized и
    // no-stretch). До правки функция возвращала бы −1 и оставляла дыру.
    expect(fillTargetIndex([false, true])).toBe(0);
  });

  it('несколько нерастяжимых подряд в хвосте — берётся ближайшая слева', () => {
    expect(fillTargetIndex([false, true, true])).toBe(0);
  });

  it('нерастяжимая в СЕРЕДИНЕ ряда не мешает: растёт та, что правее её', () => {
    expect(fillTargetIndex([false, true, false])).toBe(2);
  });

  it('ряд целиком из карточек со своим размером законно короткий', () => {
    expect(fillTargetIndex([true, true])).toBe(-1);
  });

  it('пустой ряд не выбирает никого', () => {
    expect(fillTargetIndex([])).toBe(-1);
  });
});
