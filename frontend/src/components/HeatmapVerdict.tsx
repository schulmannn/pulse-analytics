import type { JSX } from 'react';

/**
 * Строка-вердикт над тепловой картой: сначала ответ, потом доказательство.
 *
 * ЗАЧЕМ. Карточку «когда публиковать» открывают ради ОДНОГО факта, а он печатался ПОД сеткой из
 * 168 клеток — то есть после всего доказательства и, у скринридера, после ста с лишним ячеек.
 * Референс Clearful ставит вердикт над графиком активности; берём узко — строкой, без карточек с
 * заливкой (в тайле нет места, а заливка нарушила бы «один акцент», DESIGN_TOKENS).
 *
 * ДВА КОНЦА ШКАЛЫ. «Пик» без «затишья» — половина ответа: час без активности узнать по бледной
 * клетке нельзя (бледная = «мало» и «нет данных» одновременно). Затишье приходит уже отфильтрованным
 * слоем данных и может быть `null` — тогда строка честно молчит вторым сегментом, а не выдумывает
 * худший слот из одного наблюдения.
 *
 * ЦВЕТА НЕТ. Ни у пика, ни у затишья: оценочный цвет в продукте занят дельтой рейла сравнения.
 * Иерархию внутри строки даёт оттенок (foreground против muted), а не вес и не краска.
 */
export function HeatmapVerdict({
  peak,
  quiet,
}: {
  /** `value` приходит УЖЕ отформатированным («1.2k онлайн», «ERV 4.8% по 6 постам»): у TG и IG
      разные единицы, и склеивать их здесь значило бы завести в компоненте знание об источниках. */
  peak: { day: string; hour: number; value: string } | null;
  quiet: { day: string; hour: number; value: string } | null;
}): JSX.Element | null {
  // Нет пика — нет и вердикта: строка «Пик · —» заняла бы место, ничего не сказав. О причине
  // (мало постов, метрика пуста) сообщает сама карточка под сеткой.
  if (!peak) return null;
  return (
    <p data-slot="heatmap-verdict" className="mb-2 text-xs text-muted-foreground">
      Пик ·{' '}
      <span className="font-medium tabular-nums text-foreground">
        {peak.day} {peak.hour}:00
      </span>{' '}
      · {peak.value}
      {quiet ? (
        // Второй сегмент уходит только в РЕАЛЬНО узком слоте (tile-narrow — контейнерный запрос к
        // тайлу, а не к экрану). Обратный гейт «показать в широком тайле» здесь неверен: на
        // /metrics/tg-heatmap и /metrics/ig-best-time контейнера `tile` нет вовсе, запрос к
        // несуществующему контейнеру ложен всегда — и затишье пропало бы ровно на самых широких
        // страницах продукта.
        <span className="tile-narrow:hidden">
          {' '}
          — Тише всего ·{' '}
          <span className="font-medium tabular-nums text-foreground">
            {quiet.day} {quiet.hour}:00
          </span>{' '}
          · {quiet.value}
        </span>
      ) : null}
    </p>
  );
}
