/**
 * `placeholderData` для ОКОННЫХ чтений: пока грузится новое окно того же канала, предыдущее
 * остаётся смонтированным.
 *
 * Зачем. Смена периода перек-лючает queryKey, и без этого карточка на мгновение теряет данные:
 * график размонтируется, MorphingSeries нечего интерполировать, раскрытая карточка фильтра
 * захлопывается, а на месте чисел мигает скелетон. Для TG и IG это чинили точечно (#313), а
 * девятнадцать оконных хуков МойСклада, Метрики, СДЭКа и упоминаний остались со скелетоном —
 * то есть один и тот же жест давал разное поведение в зависимости от источника.
 *
 * Граница. Данные НИКОГДА не переносятся между каналами: иначе на экране мелькнут числа чужого
 * источника, а это прямое нарушение инварианта «выбранный источник не меняется сам собой».
 * Проверка идёт по ВТОРОМУ элементу ключа — во всех этих семьях там channelId (см. queryKeys.ts).
 *
 * Свежесть. Подставленные данные не считаются свежими: TanStack помечает их `isPlaceholderData`,
 * а `dataUpdatedAt` остаётся от прошлого ответа — индикатор «обновлено N мин назад» продолжает
 * говорить правду о ПРОШЛОМ окне, а не выдаёт старое за новое.
 */
export const keepPreviousForChannel =
  (channelId: number | null) =>
  <T>(previous: T | undefined, previousQuery: { queryKey: readonly unknown[] } | undefined): T | undefined =>
    previousQuery?.queryKey[1] === channelId ? previous : undefined;
